-- Lectura pública, sin escritura desde el cliente (igual que beneficios). Se revisa cada mes.
-- La app oculta sola lo que ya cerró (cierre) o ya pasó (fecha).

create table if not exists public.convocatorias (
  id uuid primary key default gen_random_uuid(),
  tipo text not null check (tipo in ('convocatoria', 'evento', 'feria')),
  nombre text not null,
  organizador text not null,
  resumen text not null,
  detalle text,
  requisito text,
  como text[] not null default '{}',
  pago text,
  costo text,
  lugar text,
  fecha date,
  hora_texto text,
  cierre timestamptz,
  link text,
  fuente text not null,
  verificado_en date not null,
  orden int not null default 100,
  activo boolean not null default true,
  created_at timestamptz not null default now()
);
alter table public.convocatorias enable row level security;
create policy "convocatorias lectura publica" on public.convocatorias for select to anon, authenticated using (true);
revoke insert, update, delete on public.convocatorias from anon, authenticated;
grant select on public.convocatorias to anon, authenticated;

